/*
 * Our own copy: what each ingredient does, in words a shopper can use.
 *
 * The register gives us provenance and nothing a customer can read. This is the
 * other half, written by hand, and it is written only for ingredients we can
 * describe accurately. There are 21,897 entries in the register and most of them
 * are specific plant extracts and rare chemicals; inventing a benefit for those
 * would put a sentence on a product page with nothing behind it. So this covers
 * the ingredients that actually appear on labels, and the rest stay blank until
 * someone can write them honestly.
 *
 * What the wording avoids, deliberately: 주름 개선, 미백 and 자외선 차단 are
 * 기능성 claims under 화장품법, allowed for a product only after 심사 or 보고.
 * Where an ingredient is itself a 고시 기능성 원료 that fact is stated as a fact
 * about the ingredient — which is true and checkable — and never as a promise
 * about a formula it happens to be in. Nothing here describes treating a
 * condition.
 *
 * This batch: the things that hold water, seal it in, and carry the rest of the
 * formula. They make up most of the front of almost every Korean label.
 */

/*
 * Names that matched nothing, kept rather than lost.
 *
 * The copy is attached by normalised name, so a standard name spelled even
 * slightly differently from the Ministry's updates no rows — and an UPDATE that
 * matches nothing is silent. Rather than trust 180 spellings, every entry that
 * finds no ingredient is recorded here, so the gap is visible and the writing is
 * not thrown away.
 */
create table if not exists public.ingredient_copy_unmatched (
  kor_name  text primary key,
  role      text,
  ko        text,
  added_at  timestamptz not null default now()
);


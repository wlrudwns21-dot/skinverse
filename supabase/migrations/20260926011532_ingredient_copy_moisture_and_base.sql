upd as (
  update public.ingredients i
     set role  = e.role,
         blurb = jsonb_build_object('ko', e.ko)
    from entries e
   where i.match_key = public.ingredient_key(e.kor_name)
  returning e.kor_name
)
insert into public.ingredient_copy_unmatched (kor_name, role, ko)
select e.kor_name, e.role, e.ko
  from entries e
 where not exists (select 1 from upd u where u.kor_name = e.kor_name)
on conflict (kor_name) do update
  set role = excluded.role, ko = excluded.ko, added_at = now();
